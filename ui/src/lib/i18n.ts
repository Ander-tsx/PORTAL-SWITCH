const tables = { en, es }
export type Lang = keyof typeof tables

export function detectLang(): Lang {
  const wanted = (typeof navigator !== 'undefined' ? navigator.language : 'en').slice(0, 2)
  return wanted in tables ? (wanted as Lang) : 'en'
}

export function translator(lang: Lang) {
  return (key: Key, vars: Record<string, string> = {}): string =>
    Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, v), tables[lang][key])
}
